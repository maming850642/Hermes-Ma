# 决策：对比新事实与已有相似记忆，决定 ADD/UPDATE/DELETE/NOOP
DECIDE_PROMPT = """你是记忆管理器。对比新事实与已有的相似记忆，为每条新事实决定操作。

## 操作定义
- ADD: 全新信息，记忆库没有类似的 → 新增
- UPDATE: 已有相似记忆，新信息补充/修正了它 → 合并成一条更完整的记忆
- DELETE: 新信息与已有记忆直接矛盾 → 删除旧的（如"不喜欢"否定"喜欢"）
- NOOP: 新信息与已有记忆内容完全相同 → 无需操作

## 核心判断：UPDATE 还是 DELETE？
**总原则:拿不准矛盾时一律 UPDATE,绝不误 DELETE——误删一条正确记忆的代价远大于多留一条。**
这是最容易出错的地方，务必区分清楚：
- **UPDATE（补充/细化）**：新旧信息可以同时成立，新信息让旧记忆更完整或更精确。
  - 旧"用户喜欢 Python" + 新"用户主要用 Python 做数据分析" → UPDATE 合并为"用户喜欢 Python，主要做数据分析"
  - 旧"用户住在北京" + 新"用户在海淀工作" → UPDATE 合并为"用户住在北京，在海淀工作"
- **DELETE（矛盾/推翻）**：新旧信息不能同时成立，新信息直接否定旧记忆。
  - 旧"用户喜欢爬山" + 新"用户不喜欢爬山" → DELETE 旧记忆
  - 旧"用户用 React" + 新"用户已改用 Vue" → DELETE 旧记忆（"改用"表示推翻）
- **区分信号**："也"、"还"、"主要"、"在…方面"多为补充（UPDATE）；"不"、"改用"、"换成了"、"其实不喜欢"多为否定（DELETE）。
- 宁可 UPDATE 也不要误 DELETE：拿不准矛盾时优先 UPDATE，保留两条信息合并。

## 其他规则
- UPDATE 时把新旧信息合并成一条完整、不重复、自然通顺的文本。
- DELETE 仅用于明确的语义矛盾，不要因措辞不同就 DELETE。
- NOOP 要严格：语义完全等价才标 NOOP（"用户叫小明" vs "用户的名字是小明" → NOOP）。
- 处理时间衰减：旧记忆带过期时间限定、新信息表明已变化 → DELETE 旧（如旧"下周出差" + 新"出差取消了"）。

## 示例

输入：
新事实：["用户偏好 snake_case 命名"]
旧记忆：[{{"id": "m1", "content": "用户偏好 camelCase 命名"}}]
输出：{{"decisions": [{{"action": "DELETE", "content": "", "target_id": "m1"}}]}}
（"偏好 snake_case"否定了"偏好 camelCase"，矛盾 → DELETE）

输入：
新事实：["用户主要做数据分析"]
旧记忆：[{{"id": "m1", "content": "用户喜欢 Python"}}]
输出：{{"decisions": [{{"action": "UPDATE", "content": "用户喜欢 Python，主要用 Python 做数据分析", "target_id": "m1"}}]}}
（补充信息，可共存 → UPDATE 合并）

输入：
新事实：["用户叫小明"]
旧记忆：[{{"id": "m1", "content": "用户叫小明"}}]
输出：{{"decisions": [{{"action": "NOOP", "content": "", "target_id": null}}]}}
（语义完全相同 → NOOP）

## 输入
新事实列表:
{new_facts_json}

已有相似记忆（每条带 id 和内容）:
{old_memories_json}

## 输出格式
严格输出 JSON：{{"decisions": [{{"action": "ADD|UPDATE|DELETE|NOOP", "content": "决策后的文本", "target_id": "UPDATE/DELETE 时填旧记忆 id，否则 null"}}]}}
- ADD 的 content = 新事实原文
- UPDATE 的 content = 合并后的完整文本，target_id 指向被合并的旧记忆
- DELETE 的 content 留空，target_id 指向被删除的旧记忆
- NOOP 的 content 留空，target_id 留 null
- 拿不准矛盾时优先 UPDATE 而非 DELETE
- 只输出 JSON，不要任何解释
"""

